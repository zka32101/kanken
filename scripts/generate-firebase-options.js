#!/usr/bin/env node

/**
 * Firebase Options Generator
 *
 * 用途: google-services.json から firebase_options.dart を生成
 * 使い方: node scripts/generate-firebase-options.js [PROJECT_ID]
 */

const fs = require('fs');
const path = require('path');

// 色定義
const colors = {
  reset: '\x1b[0m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
};

function log(color, message) {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

// google-services.json を読み込む
function loadGoogleServices() {
  const filepath = path.join(__dirname, '../android/app/google-services.json');

  if (!fs.existsSync(filepath)) {
    log('red', `❌ google-services.json が見つかりません: ${filepath}`);
    process.exit(1);
  }

  try {
    const content = fs.readFileSync(filepath, 'utf8');
    return JSON.parse(content);
  } catch (error) {
    log('red', `❌ google-services.json の解析に失敗: ${error.message}`);
    process.exit(1);
  }
}

// firebase_options.dart を生成
function generateFirebaseOptions(googleServices) {
  const projectInfo = googleServices.project_info;
  const client = googleServices.client[0];
  const androidInfo = client.client_info.android_client_info;
  const apiKey = client.api_key[0]?.current_key || 'YOUR_ANDROID_API_KEY';

  const mobileSdkAppId = client.client_info.mobilesdk_app_id;
  const messagingSenderId = projectInfo.project_number;
  const projectId = projectInfo.project_id;

  // android_client_info から appId を取得 (format: "1:NUMBER:android:HEX")
  const appId = mobileSdkAppId;

  const template = `// This file was auto-generated by generate-firebase-options.js
// Do not edit this file manually. Instead, update google-services.json
// and run: node scripts/generate-firebase-options.js

import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      return web;
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      case TargetPlatform.macOS:
        return macos;
      case TargetPlatform.windows:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for windows - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      case TargetPlatform.linux:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for linux - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      default:
        throw UnsupportedError(
          'DefaultFirebaseOptions are not supported for this platform.',
        );
    }
  }

  static const FirebaseOptions web = FirebaseOptions(
    apiKey: 'YOUR_WEB_API_KEY',
    appId: 'YOUR_WEB_APP_ID',
    messagingSenderId: 'YOUR_MESSAGING_SENDER_ID',
    projectId: '${projectId}',
    authDomain: '${projectId}.firebaseapp.com',
    databaseURL: '${projectInfo.firebase_url}',
    storageBucket: '${projectInfo.storage_bucket}',
  );

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '${apiKey}',
    appId: '${appId}',
    messagingSenderId: '${messagingSenderId}',
    projectId: '${projectId}',
    databaseURL: '${projectInfo.firebase_url}',
    storageBucket: '${projectInfo.storage_bucket}',
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: 'YOUR_IOS_API_KEY',
    appId: 'YOUR_IOS_APP_ID',
    messagingSenderId: 'YOUR_MESSAGING_SENDER_ID',
    projectId: '${projectId}',
    databaseURL: '${projectInfo.firebase_url}',
    storageBucket: '${projectInfo.storage_bucket}',
  );

  static const FirebaseOptions macos = FirebaseOptions(
    apiKey: 'YOUR_MACOS_API_KEY',
    appId: 'YOUR_MACOS_APP_ID',
    messagingSenderId: 'YOUR_MESSAGING_SENDER_ID',
    projectId: '${projectId}',
    databaseURL: '${projectInfo.firebase_url}',
    storageBucket: '${projectInfo.storage_bucket}',
  );
}
`;

  return template;
}

// メイン処理
function main() {
  log('blue', '🔥 Firebase Options Generator\n');

  log('yellow', '📖 google-services.json を読み込み中...');
  const googleServices = loadGoogleServices();
  log('green', '✓ google-services.json を読み込みました\n');

  log('yellow', '⚙️  firebase_options.dart を生成中...');
  const content = generateFirebaseOptions(googleServices);

  const outputPath = path.join(__dirname, '../lib/firebase_options.dart');
  fs.writeFileSync(outputPath, content, 'utf8');

  log('green', `✓ firebase_options.dart を生成しました: ${outputPath}\n`);

  // 検証
  log('blue', '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  log('blue', '📋 生成された設定:');
  log('blue', '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

  const projectInfo = googleServices.project_info;
  console.log(`  Project ID:        ${projectInfo.project_id}`);
  console.log(`  Project Number:    ${projectInfo.project_number}`);
  console.log(`  Firebase URL:      ${projectInfo.firebase_url}`);
  console.log(`  Storage Bucket:    ${projectInfo.storage_bucket}`);
  console.log(`  Mobile SDK App ID: ${googleServices.client[0].client_info.mobilesdk_app_id}`);

  log('green', '\n✅ Firebase Options が正常に生成されました!\n');
}

main();
